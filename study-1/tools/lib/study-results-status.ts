// The study block of the root README's "Repository status" (close-out, the owner's item 4): every
// number and status the README states about the study, read from the derived results, never typed
// by hand. The block sits between two marker lines, so `npm run results` rewrites it and
// `npm run results -- --check` fails when the README drifts from a fresh derivation.

import type { ExcludedExecution, ExecutionResult } from './study-results-execution.ts';
import type { TrialResult } from './study-results-trial.ts';
import type { StudyResults } from './study-results.ts';

export const STATUS_BEGIN =
  '<!-- study-results:begin; generated by `npm run results` in study-1/ from results/study-1/results.json, do not edit -->';
export const STATUS_END = '<!-- study-results:end -->';

/**
 * The README's study block for `results`, ending with a newline, without the marker lines.
 *
 * @example
 * repositoryStatus(deriveStudyResults(input)).startsWith('Every value in this block'); // true
 */
export function repositoryStatus(results: StudyResults): string {
  const lines = [
    'Every value in this block is read from [`results/study-1/results.json`](results/study-1/results.json).',
    '',
    ...results.canonical_runs.flatMap(canonicalRunLines),
    `Within-variant reproductions, never comparative: ${listOrNone(results.within_variant_reproductions.map(reproductionText), '; ')}.`,
    '',
    `Excluded by the reproduction criterion: ${listOrNone(results.excluded_executions.map(excludedText), '; ')}.`,
  ];
  return `${lines.join('\n')}\n`;
}

/**
 * `readme` with the text between its marker lines replaced by `status`, refused unless the README
 * holds exactly one begin marker before exactly one end marker.
 *
 * @example
 * withRepositoryStatus(`${STATUS_BEGIN}\nold\n${STATUS_END}\n`, 'new\n'); // `${STATUS_BEGIN}\nnew\n${STATUS_END}\n`
 */
export function withRepositoryStatus(readme: string, status: string): string {
  const begins = readme.split(STATUS_BEGIN).length - 1;
  const ends = readme.split(STATUS_END).length - 1;
  const begin = readme.indexOf(STATUS_BEGIN);
  // Searched from the begin marker: an end marker before it is not found.
  const end = readme.indexOf(STATUS_END, begin);
  if (begins !== 1 || ends !== 1 || end === -1) {
    throw new Error(
      `the README holds ${String(begins)} begin and ${String(ends)} end study-results markers; ` +
        `expected one "${STATUS_BEGIN}" line before one "${STATUS_END}" line`,
    );
  }
  return `${readme.slice(0, begin + STATUS_BEGIN.length)}\n${status}${readme.slice(end)}`;
}

function canonicalRunLines(run: ExecutionResult): readonly string[] {
  const valid = run.trials.filter((trial) => trial.trial_validity === 'valid').length;
  const dates = [...new Set(run.trials.flatMap((trial) => trial.commit_times.map((time) => time.slice(0, 10))))];
  return [
    `The canonical run \`${shortId(run.execution_id)}\` ran ${String(run.trials.length)} trials from source commit ` +
      `\`${run.source_commit.slice(0, 7)}\`, qualified by transport probe \`${shortId(run.selected_probe.transport_probe_id)}\`; ` +
      `refund commit dates (UTC): ${listOrNone(dates.sort(), ', ')}. ${String(valid)} of the ${String(run.trials.length)} trials were valid. ` +
      `Outcome: ${statuses(run.outcome)}. Closure: ${statuses(run.closure)}.`,
    '',
    `Inputs of every trial: approved \`${run.inputs.approved_amount_minor}\` and captured ` +
      `\`${run.inputs.captured_amount_minor}\` minor units of \`${run.inputs.currency}\`, in Region \`${run.inputs.region}\`. ` +
      `Estimated cost before billing: \`${run.safety.estimated_cost.observed_usd}\` USD against a ` +
      `\`${run.safety.estimated_cost.declared_limit_usd}\` USD limit (\`${run.safety.estimated_cost.result}\`).`,
    '',
    '| Trial | Scenario | Variant | Successful provider transactions | Refunded, in minor units | Preservation verdict |',
    '|---|---|---|---|---|---|',
    ...run.trials.map(
      (trial) =>
        `| ${String(trial.sequence)} | \`${trial.scenario}\` | \`${trial.variant_id}\` | ` +
        `${String(trial.successful_transaction_count)} | ${refunded(trial)} | \`${trial.preservation_verdict}\` |`,
    ),
    '',
  ];
}

function reproductionText(execution: ExecutionResult): string {
  const verdicts = execution.trials.map((trial) => `\`${trial.scenario}\` \`${trial.preservation_verdict}\``);
  return `\`${shortId(execution.execution_id)}\` (${variantsOf(execution.trials)}): ${verdicts.join(', ')}`;
}

function excludedText(execution: ExcludedExecution): string {
  return `\`${shortId(execution.execution_id)}\` (${variantsOf(execution.trials)}): ${statuses(execution.outcome)}`;
}

function variantsOf(trials: readonly { readonly variant_id: string }[]): string {
  return [...new Set(trials.map((trial) => `\`${trial.variant_id}\``))].join(', ');
}

function statuses(members: Readonly<Record<string, string>>): string {
  return Object.entries(members)
    .map(([name, value]) => `${name} \`${value}\``)
    .join(', ');
}

function refunded(trial: TrialResult): string {
  return trial.currency === null ? trial.refunded_total_minor : `${trial.refunded_total_minor} ${trial.currency}`;
}

function listOrNone(items: readonly string[], separator: string): string {
  return items.length === 0 ? 'none' : items.join(separator);
}

// The first eight hex digits, as the study's records and reports name executions.
function shortId(id: string): string {
  return id.slice(0, 8);
}
