const at = (text: string): UtcMillis => text as UtcMillis;

/** What a case varies in the closure the base run reaches. */
export interface ClosureSpec {
  readonly cleanup_status: 'succeeded' | 'failed';
  readonly leaks: readonly LeakedResource[];
  /** The last lease event the coordination journal records (design §10.3 finalize). */
  readonly final_lease_event: Extract<LeaseEvent, 'RELEASED' | 'RECOVERY_REQUIRED'>;
}

/** The clean closure of AC-RUA-027: cleanup succeeded, audit clean, lease released. */
export const CLEAN_CLOSURE: ClosureSpec = { cleanup_status: 'succeeded', leaks: [], final_lease_event: 'RELEASED' };

/**
 * Every operation that turns the base into a frozen, closed run package.
 *
 * @example
 * defineGoldenCase({ ..., base: 'run-durable-treatment', operations: frozenRunOperations(BASE_TRANSACTIONS, CLEAN_CLOSURE) });
 */
export function frozenRunOperations(
  transactions: readonly (readonly Uuid4[])[],
  closure: ClosureSpec,
): readonly ScenarioOperation[] {
  return [
    ...oracleResultOperations(transactions),
    putJson(EXECUTION_PATHS.sourceProvenance, sourceProvenance()),
    // The manifest pins the provenance by digest (BR-RUA-042); linking keeps the pin exact.
    {
      op: 'set',
      path: EXECUTION_PATHS.executionManifest,
      pointer: '/source/source_provenance_sha256',
      value: linkSha256(EXECUTION_PATHS.sourceProvenance),
    },
    putJson(EXECUTION_PATHS.lateEvidenceAssessment, quietLateEvidence()),
    putJson(EXECUTION_PATHS.cleanupResult, cleanupResult(closure.cleanup_status)),
    putJson(EXECUTION_PATHS.leakAuditResult, leakAudit(closure.leaks)),
    putJson(EXECUTION_PATHS.safetyAssessment, withinLimitsSafety()),
    {
      op: 'put_file',
      path: EXECUTION_PATHS.coordinationJournal,
      content: {
        kind: 'jsonl',
        records: [
          recordJson(leaseEvent(1, 'ACQUIRED', at('2026-10-05T12:00:00.500Z'))),
          recordJson(leaseEvent(2, closure.final_lease_event, at('2026-10-05T13:14:00.000Z'))),
        ],
      },
    },
  ];
}

/**
 * The oracle result of each declared trial, judged on the given ledger transactions.
 *
 * @example
 * oracleResultOperations(BASE_TRANSACTIONS); // four put_file operations
 */
export function oracleResultOperations(transactions: readonly (readonly Uuid4[])[]): readonly ScenarioOperation[] {
  return RUN_TRIALS.map((trial, index) => {
    const unit = { kind: 'trial', trial_id: trial.trial_id } as const;
    const result = validOracleResult({
      run_id: RUN_ID,
      trial,
      execution_manifest_sha256: MANIFEST_DIGEST,
      trial_manifest_sha256: linkSha256(PACKAGE_LAYOUT.unitFile(unit, 'trialManifest')),
      provider_transaction_ids: transactions[index] ?? [],
      digest_of: linkSha256,
      checked_at: at('2026-10-05T12:56:00.000Z'),
    });
    return putJson(PACKAGE_LAYOUT.unitFile(unit, 'oracleResult'), result);
  });
}

