function putJson(path: string, record: StudyRecord): ScenarioOperation {
  return { op: 'put_file', path, content: { kind: 'json', record: recordJson(record) } };
}

// Typed records are JSON by construction; their interfaces only lack an index signature.
function recordJson(record: StudyRecord): JsonValue {
  return record as unknown as JsonValue;
}

