function leakAudit(leaks: readonly LeakedResource[]): LeakAuditResult {
  const pass = (start: string, end: string): LeakAuditResult['passes'][number] => ({
    started_at: at(start),
    completed_at: at(end),
    surfaces: [
      { surface: 'tag_index', query_ok: true, observed: leaks.map((leak) => leak.identifier) },
      { surface: 'functions', query_ok: true, observed: [] },
    ],
  });
  return {
    schema_version: 1,
    record_type: 'leak_audit_result',
    ...RUN_CORRELATION,
    leak_audit_status: leaks.length === 0 ? 'clean' : 'leaks_detected',
    passes: [
      pass('2026-10-05T13:10:30.000Z', '2026-10-05T13:10:40.000Z'),
      pass('2026-10-05T13:12:40.000Z', '2026-10-05T13:12:50.000Z'),
    ],
    leaks,
    ambiguous: [],
    stable_absence_interval_ms: leaks.length === 0 ? 120_000 : 0,
    audited_at: at('2026-10-05T13:12:50.000Z'),
  };
}

